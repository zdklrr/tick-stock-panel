def _decode(text: str) -> tuple[str, ...]:
    """双字符下标串 → 概念名元组。"""
    out: list[str] = []
    for pos in range(0, len(text) - 1, 2):
        head = _ALPHABET.find(text[pos])
        tail = _ALPHABET.find(text[pos + 1])
        out.append(CONCEPT_NAMES[head * 36 + tail])
    return tuple(out)


def _build() -> dict[str, tuple[str, ...]]:
    """``CODE_CONCEPTS`` → ``{6 位代码: (概念, ...)}``。"""
    out: dict[str, tuple[str, ...]] = {}
    for entry in CODE_CONCEPTS:
        out[entry[:6]] = _decode(entry[6:])
    return out


_CODE_TO_CONCEPTS: dict[str, tuple[str, ...]] | None = None


def concept_map() -> dict[str, tuple[str, ...]]:
    """``{6 位代码: (概念, ...)}``（进程内单例）。"""
    global _CODE_TO_CONCEPTS
    if _CODE_TO_CONCEPTS is None:
        _CODE_TO_CONCEPTS = _build()
    return _CODE_TO_CONCEPTS


def concepts_of(symbol: str) -> tuple[str, ...]:
    """按 symbol 取概念元组；未收录返回空元组（缺表即降级为「无题材」）。"""
    return concept_map().get(str(symbol or "").strip()[:6], ())


def stats() -> dict[str, int]:
    """诊断用：代码数 / 概念数 / 归属对数。"""
    mapping = concept_map()
    concepts = {c for cs in mapping.values() for c in cs}
    return {
        "codes": len(mapping),
        "concepts": len(concepts),
        "pairs": sum(len(cs) for cs in mapping.values()),
    }
